"""FloodGuard R2: all flash images below are GENERATED SYNTHETIC TEST DATA."""
from pathlib import Path
import hashlib
import importlib.util
import json
import os
import subprocess
import sys
import tempfile
import unittest

HERE = Path(__file__).resolve().parents[1]
SCRIPT = HERE / "experiments/esp8266-core-excl-review/r2_private_backup_pair.py"
spec = importlib.util.spec_from_file_location("fg_private_copies", SCRIPT)
gate = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gate)


def fake_boards():
    lines = ["nodemcuv2.name=NodeMCU 1.0 (ESP-12E Module)"]
    for name, start in (("4M1M",0x300000),("4M2M",0x200000),("4M3M",0x100000),("4M",None)):
        base = "nodemcuv2.menu.eesz."+name+".build."
        lines.extend([base+"flash_ld=eagle.flash."+name.lower()+".ld",base+"flash_size=4M"])
        if start is not None:
            lines.extend([base+"spiffs_start="+hex(start),base+"spiffs_end=0x3fa000"])
    return ("\n".join(lines)+"\n").encode()


def manifest(sha):
    return {
        "schema":"floodguard-r2-board-evidence-v1",
        "origin":"operator-observed",  # synthetic fixture ONLY
        "core_version":"3.1.2",
        "fqbn":"esp8266:esp8266:nodemcuv2",
        "selected_flash_menu":"4M1M",
        "selected_flash_ld":"eagle.flash.4m1m.ld",
        "real_flash_bytes":4194304,
        "configured_flash_bytes":4194304,
        "filesystem_start":0x300000,
        "filesystem_end":0x3fa000,
        "bench_isolated":True,
        "actuators_disconnected":True,
        "read_only_observation":True,
        "independent_partition_review":True,
        "backup":{
            "size_bytes":4194304,
            "sha256":sha,
            "second_read_sha256":sha,
            "stored_privately":True,
        }
    }


class BackupPairTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp = tempfile.TemporaryDirectory(prefix="fg-synthetic-not-hardware-")
        cls.root = Path(cls.temp.name)
        cls.first = cls.root / "a.bin"
        cls.second = cls.root / "b.bin"
        # Generated bytes with recognizable synthetic marker, NOT board flash.
        marker=b"FG-SYNTHETIC-RAM-ONLY-NO-SENSOR-"
        sample=(marker * ((4194304 // len(marker)) + 1))[:4194304]
        cls.first.write_bytes(sample)
        cls.second.write_bytes(sample)
        cls.digest=hashlib.sha256(sample).hexdigest()
        cls.sdk=fake_boards()
        cls.old_pin=gate.board.PINNED_BOARDS_GIT_BLOB
        gate.board.PINNED_BOARDS_GIT_BLOB=gate.board.git_blob_sha(cls.sdk)

    @classmethod
    def tearDownClass(cls):
        gate.board.PINNED_BOARDS_GIT_BLOB=cls.old_pin
        cls.temp.cleanup()

    def good(self, data=None, first=None, second=None):
        evidence=manifest(self.digest) if data is None else data
        return gate.examine(self.sdk,json.dumps(evidence).encode(),
                            str(self.first if first is None else first),
                            str(self.second if second is None else second))

    def test_identical_synthetic_copies_still_deny_hardware_operation(self):
        output=self.good()
        self.assertEqual(output["evidence_status"],
                         "LOCAL_COPIES_IDENTICAL_NOT_PHYSICAL_PROOF")
        for k in ("independent_hardware_reads_proven","deployed_flash_layout_proven",
                  "may_mount","may_write","may_flash","may_publish","may_ack",
                  "may_operate_gate","production_go"):
            self.assertIs(output[k],False)
        self.assertNotIn(self.digest,json.dumps(output))
        self.assertNotIn(str(self.root),json.dumps(output))

    def test_identical_bytes_not_same_inode(self):
        with self.assertRaisesRegex(gate.EvidenceError,"COPIES_SHARE_SAME_FILE"):
            self.good(second=self.first)

    def test_hardlinked_copy_refused(self):
        linked=self.root/"same-inode.bin"
        try:
            os.link(self.first,linked)
            with self.assertRaisesRegex(gate.EvidenceError,"COPIES_SHARE_SAME_FILE"):
                self.good(second=linked)
        finally:
            linked.unlink(missing_ok=True)

    def test_symlink_not_followed(self):
        linked=self.root/"symlink.bin"
        linked.symlink_to(self.first)
        try:
            with self.assertRaisesRegex(gate.EvidenceError,"LOCAL_COPY_CANNOT_BE_OPENED"):
                self.good(second=linked)
        finally:
            linked.unlink(missing_ok=True)

    def test_directory_rejected(self):
        with self.assertRaisesRegex(gate.EvidenceError,"NOT_A_REGULAR_BACKUP_COPY"):
            self.good(second=self.root)

    def test_different_bytes_fail_without_offsets(self):
        changed=self.root/"mutated.bin"
        img=bytearray(self.first.read_bytes())
        img[123456]^=1
        changed.write_bytes(img)
        try:
            with self.assertRaisesRegex(gate.EvidenceError,"LOCAL_BACKUP_BYTES_MISMATCH"):
                self.good(second=changed)
        finally:
            changed.unlink(missing_ok=True)

    def test_short_backup_fails_closed(self):
        short=self.root/"short.bin"
        short.write_bytes(b"short")
        try:
            with self.assertRaisesRegex(gate.EvidenceError,"BACKUP_SIZE_CONFLICT"):
                self.good(second=short)
        finally:
            short.unlink(missing_ok=True)

    def test_expected_backup_digest_must_match_content(self):
        data=manifest("a"*64)
        with self.assertRaisesRegex(gate.EvidenceError,"MANIFEST_BACKUP_HASH_MISMATCH"):
            self.good(data)

    def test_missing_private_backup_assertion_fails_before_file_read(self):
        data=manifest(self.digest)
        data["backup"]["stored_privately"]=False
        with self.assertRaisesRegex(gate.EvidenceError,"SOURCE_MANIFEST_NOT_REVIEW_READY"):
            self.good(data)

    def test_no_filesystem_layout_rejected(self):
        data=manifest(self.digest)
        data["selected_flash_menu"]="4M"
        data["selected_flash_ld"]="eagle.flash.4m.ld"
        data["filesystem_start"]=None
        data["filesystem_end"]=None
        with self.assertRaisesRegex(gate.EvidenceError,
                                     "SOURCE_MANIFEST_NOT_REVIEW_READY"):
            self.good(data)

    def test_source_blob_mutation_fails(self):
        with self.assertRaisesRegex(gate.EvidenceError,"SOURCE_OR_MANIFEST_INVALID"):
            gate.examine(self.sdk+b"#tampered\n",
                         json.dumps(manifest(self.digest)).encode(),
                         str(self.first),str(self.second))

    def test_sensitive_unexpected_manifest_fields_blocked(self):
        data=manifest(self.digest)
        data["secret_token"]="do-not-print-test-secret"
        with self.assertRaisesRegex(gate.EvidenceError,"SOURCE_MANIFEST_NOT_REVIEW_READY"):
            self.good(data)

    def test_bad_json_duplicate_fields_blocked(self):
        with self.assertRaisesRegex(gate.EvidenceError,"SOURCE_OR_MANIFEST_INVALID"):
            gate.examine(self.sdk,b'{"schema":"x","schema":"y"}',
                         str(self.first),str(self.second))

    def test_relative_paths_refused(self):
        with self.assertRaisesRegex(gate.EvidenceError,"UNSUPPORTED_OR_NONABSOLUTE_INPUT"):
            self.good(first="a.bin")

    def test_out_of_scope_and_boolean_length_rejected(self):
        for n in (0,True,-1,gate.MAX_BYTES+1):
            with self.subTest(value=n):
                with self.assertRaisesRegex(gate.EvidenceError,"BACKUP_SIZE_OUT_OF_SCOPE"):
                    gate.compare_copies(str(self.first),str(self.second),n)

    def test_cli_failure_never_prints_paths_hash_or_secret(self):
        boards=self.root/"not-the-pinned-sdk.txt"
        evidence=self.root/"private-evidence.json"
        boards.write_bytes(self.sdk)
        evidence.write_text(json.dumps(manifest(self.digest)),"utf-8")
        completed=subprocess.run(
            [sys.executable,str(SCRIPT),"--boards",str(boards),
             "--manifest",str(evidence),"--first",str(self.first),
             "--second",str(self.second)],capture_output=True,text=True,check=False)
        self.assertEqual(completed.returncode,2)
        report=json.loads(completed.stdout)
        self.assertEqual(report["finding_codes"],["SOURCE_OR_MANIFEST_INVALID"])
        self.assertNotIn(str(self.root),completed.stdout+completed.stderr)
        self.assertNotIn(self.digest,completed.stdout+completed.stderr)
        self.assertFalse(report["production_go"])


if __name__=="__main__":
    unittest.main(verbosity=2)
